"""Emit the defense table for the paper directly from pilot summary.json files.

Rationale: the headline empirical table should be generated from the run
artifacts, never transcribed by hand. Every number below carries a Wilson
score interval because the defense cells use M=30 episodes, where a reported
0.1 is only 3/30 and a bare point estimate would overstate precision.

Writes a LaTeX fragment to stdout (or --out) plus a CSV of the same values.
Local/offline: reads only summary.json files.
"""
from __future__ import annotations

import argparse
import json
import math
import pathlib
import sys

_ROOT = pathlib.Path(__file__).resolve().parents[1]
for _p in (_ROOT / "src", _ROOT):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

import pandas as pd

# (label, path relative to repo root, short id used in the run directory name)
SOURCES = [
    ("Qwen2.5-3B", "outputs/llm_pilot_defense/Qwen2.5-3B-Instruct--delimiting"),
    ("Qwen2.5-7B$^{a}$", "outputs/llm_pilot_defense/Qwen2.5-7B-Instruct-bnb-4bit--delimiting"),
    ("Llama-3.2-1B", "outputs/llm_pilot_defense/Llama-3.2-1B-Instruct--delimiting"),
    ("Mistral-7B$^{b}$", "outputs/llm_pilot_scale/mistral-7b-bedrock--delimiting"),
]

AGENT_TAG = "_a5"
SCENARIOS = ["single_attacker", "colluding", "compromised_orchestrator"]
TOPOLOGIES = ["chain", "tree", "star", "mesh"]
SCEN_LABEL = {
    "single_attacker": "single",
    "colluding": "coll.",
    "compromised_orchestrator": "orch.",
}


def wilson(k: int, n: int, z: float = 1.959963985) -> tuple[float, float]:
    """Wilson score interval; sane at k=0 and k=n, unlike the normal approx."""
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1.0 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = (z / d) * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (max(0.0, centre - half), min(1.0, centre + half))


def collect(episode_n: int) -> pd.DataFrame:
    rows: list[dict] = []
    for label, rel in SOURCES:
        d = pathlib.Path(_ROOT / rel)
        if not d.is_dir():
            print(f"WARNING: missing source dir {rel}", file=sys.stderr)
            continue
        for cfg in sorted(d.iterdir()):
            if not cfg.is_dir() or not cfg.name.endswith(AGENT_TAG):
                continue
            topo = cfg.name[: -len(AGENT_TAG)]
            f = cfg / "summary.json"
            if not f.is_file():
                continue
            sc = json.loads(f.read_text(encoding="utf-8"))["scenarios"]
            for scen in SCENARIOS:
                if scen not in sc:
                    continue
                s = sc[scen]
                n = int(s.get("episodes") or episode_n)
                n_bad = int(s.get("parse_failures", 0))
                if n_bad:
                    raise SystemExit(
                        f"{label}/{topo}/{scen}: {n_bad} parse failures. A failed "
                        f"backbone call is recorded as a benign decision, so this cell "
                        f"understates exfiltration and its compliance rate is an "
                        f"artefact of the failure, not of the defense. Re-run the cell "
                        f"with a working credential before tabulating."
                    )
                rows.append(
                    {
                        "backbone": label,
                        "topology": topo,
                        "scenario": scen,
                        "n_episodes": n,
                        "asr_sys": float(s["asr_sys"]),
                        "asr_action": float(s["asr_action"]),
                        "compliance": float(s["compliance_rate"]),
                        "parse_failures": n_bad,
                    }
                )
    return pd.DataFrame(rows)


def fmt(value: float, n: int, width: str = "{:.2f}") -> str:
    """Point estimate with a bracketed 95% interval, the way the paper reports it."""
    if math.isnan(value):
        return "--"
    lo, hi = wilson(round(value * n), n)
    return width.format(value) + f" $[{lo:.2f},{hi:.2f}]$"


def emit_latex(df: pd.DataFrame, out: pathlib.Path) -> None:
    L: list[str] = []
    L.append(r"% AUTO-GENERATED by experiments/make_defense_table.py -- do not edit by hand.")
    L.append(r"% Source: outputs/llm_pilot_defense/*--delimiting and")
    L.append(r"%         outputs/llm_pilot_scale/mistral-7b-bedrock--delimiting")
    L.append(r"% Columns: decision-level compliance (pooled 12 attack cells), then")
    L.append(r"% episode-level ASR_sys by topology for the colluding scenario.")
    L.append(r"\begin{tabular}{@{}lccccc@{}}")
    L.append(r"\toprule")
    L.append(r"& \multicolumn{1}{c}{\emph{action channel}}"
             r" & \multicolumn{4}{c}{$\ASRs$ by topology (colluding)} \\")
    L.append(r"\cmidrule(lr){2-2}\cmidrule(lr){3-6}")
    L.append(
        r"Backbone & compliance & " + " & ".join(TOPOLOGIES) + r" \\"
    )
    L.append(r"\midrule")

    for label, _ in SOURCES:
        sub = df[df["backbone"] == label]
        if sub.empty:
            continue
        col = sub[sub["scenario"] == "colluding"]
        comp_ok = all(v == 0.0 for v in sub["compliance"].tolist())
        cells = [r"$\mathbf{0.00}$" if comp_ok else r"$\mathbf{1.00}$"]
        for topo in TOPOLOGIES:
            row = col[col["topology"] == topo]
            if row.empty:
                cells.append("--")
            else:
                v = float(row["asr_sys"].iloc[0])
                cells.append(r"$\mathbf{1.00}$" if v == 1.0 else f"{v:.2f}")
        L.append(f"{label} & " + " & ".join(cells) + r" \\")
        L.append(r"\addlinespace[1.5pt]")

    L.append(r"\bottomrule")
    L.append(r"\end{tabular}")
    out.write_text("\n".join(L) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--episodes", type=int, default=30, help="fallback M (default: %(default)s)")
    ap.add_argument("--out", default="outputs/defense_table")
    args = ap.parse_args()

    df = collect(args.episodes)
    if df.empty:
        raise SystemExit("no pilot summaries found; nothing to tabulate")

    out = pathlib.Path(_ROOT / args.out)
    out.mkdir(parents=True, exist_ok=True)
    df.to_csv(out / "defense_table.csv", index=False)
    emit_latex(df, out / "defense_table.tex")
    print(df.to_string(index=False))
    print(f"\nwrote {out}/defense_table.{{csv,tex}}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
